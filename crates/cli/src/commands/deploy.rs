/// Write a Docker-ecosystem artifact at the project root. Regenerates files
/// from a previous run (identified by GENERATED_MARKER) but never clobbers a
/// hand-written file with the same name.
fn write_root_artifact(
    root: &std::path::Path,
    filename: &str,
    content: &str,
    json_mode: bool,
    generated_files: &mut Vec<String>,
) {
    let path = root.join(filename);
    if let Ok(existing) = std::fs::read_to_string(&path) {
        if !existing.contains(GENERATED_MARKER) {
            print_diagnostics(
                &[Diagnostic {
                    severity: Severity::Warning,
                    code: "DEPLOY_FILE_EXISTS".into(),
                    message: format!(
                        "{filename} already exists and wasn't generated by pylon — left unchanged"
                    ),
                    span: None,
                    hint: Some(format!(
                        "delete or rename {filename} and re-run to regenerate it"
                    )),
                }],
                json_mode,
            );
            return;
        }
    }
    if let Err(e) = std::fs::write(&path, content) {
        print_diagnostics(
            &[Diagnostic {
                severity: Severity::Warning,
                code: "DEPLOY_WRITE_FAILED".into(),
                message: format!("Could not write {filename}: {e}"),
                span: None,
                hint: None,
            }],
            json_mode,
        );
        return;
    }
    generated_files.push(format!("{filename} (project root)"));
}

/// Write a file into the output directory, printing a diagnostic on failure.
fn write_or_fail(out_path: &std::path::Path, filename: &str, content: &str, json_mode: bool) {
    let path = out_path.join(filename);
    if let Err(e) = std::fs::write(&path, content) {
        print_diagnostics(
            &[Diagnostic {
                severity: Severity::Warning,
                code: "DEPLOY_WRITE_FAILED".into(),
                message: format!("Could not write {filename}: {e}"),
                span: None,
                hint: None,
            }],
            json_mode,
        );
    }
}

/// Sanitize a manifest name into a valid Fly.io app name.
///
/// Fly app names must be lowercase alphanumeric with hyphens, no underscores
/// or spaces.
fn sanitize_app_name(name: &str) -> String {
    name.to_lowercase()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' {
                c
            } else {
                '-'
            }
        })
        .collect()
}

