// Shared modules for Studio extensions.
//
// The CLI bundles `studio.entry.tsx` with React left as bare imports, so an
// extension must run on the React instance that Studio runs on. The import
// map in index.html points each bare specifier at a shim module that the
// server serves under /studio/modules/. A shim re-exports the module that
// Studio put on `globalThis.__PYLON_STUDIO_MODULES__` before it loaded the
// extension.
//
// ES module exports are static, so the build writes the export list of each
// shim from the keys of the real module (`scripts/build-shims.ts`).

/** The global that holds the modules, keyed by specifier. */
export const MODULES_GLOBAL = "__PYLON_STUDIO_MODULES__";

/** Where the server serves the shims. */
export const MODULES_PATH = "/studio/modules/";

/** Each shared specifier and the file name of its shim. */
export const SHARED_MODULES = {
	react: "react.js",
	"react-dom": "react-dom.js",
	"react-dom/client": "react-dom-client.js",
	"react/jsx-runtime": "react-jsx-runtime.js",
	"react/jsx-dev-runtime": "react-jsx-dev-runtime.js",
} as const;

export type SharedSpecifier = keyof typeof SHARED_MODULES;

/** The import map that index.html must hold. */
export function importMap(): { imports: Record<string, string> } {
	return {
		imports: Object.fromEntries(
			Object.entries(SHARED_MODULES).map(([specifier, file]) => [
				specifier,
				`${MODULES_PATH}${file}`,
			]),
		),
	};
}

/** The named exports of a module: its keys that are identifiers, sorted. */
export function exportNames(mod: object): string[] {
	return Object.keys(mod)
		.filter((k) => k !== "default" && /^[A-Za-z_$][\w$]*$/.test(k))
		.sort();
}

/** The source of the shim for one specifier with the given named exports. */
export function shimSource(specifier: SharedSpecifier, names: string[]): string {
	const lines = [
		`// Generated by scripts/build-shims.ts. Re-exports the "${specifier}" that Studio loaded.`,
		`const m = globalThis.${MODULES_GLOBAL}[${JSON.stringify(specifier)}];`,
		"export default m.default ?? m;",
	];
	if (names.length > 0) {
		lines.push(`export const { ${names.join(", ")} } = m;`);
	}
	return `${lines.join("\n")}\n`;
}
